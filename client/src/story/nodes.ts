export function has(s: State, k: string) { return s.skills.includes(k); }
function learn(s: State, k: string) { if (!has(s, k)) s.skills.push(k); }

// 离中心太近的人谁都不靠，由孟老镖头教。
function nearest(s: State) {
  if (Math.hypot(s.x, s.y) < 3) return "meng";
  let best = "shen", bd = Infinity;
  for (const [k, n] of Object.entries(NPCS)) {
    const d = Math.hypot(s.x - n.x, s.y - n.y);
    if (d < bd) { bd = d; best = k; }
  }
  return best;
}
function who(k: string) { return k === "meng" ? MENG : NPCS[k]; }

// 没去的那边，按最坏的情况发生。
